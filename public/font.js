export const CHAR_W = 6; // 5 columns + 1 spacing
export const CHAR_H = 7;
export const LINE_H = 8; // 7 rows + 1 leading

// Width in pixels of `text` when drawn with drawText (no trailing spacing).
export function textWidth(text) {
  return text.length === 0 ? 0 : text.length * CHAR_W - 1;
}

// Truncates `text` to fit `maxPx`, appending a period when it had to cut.
export function fit(text, maxPx) {
  if (textWidth(text) <= maxPx) return text;
  let n = Math.floor((maxPx + 1) / CHAR_W);
  if (n <= 0) return '';
  return text.slice(0, Math.max(0, n - 1)) + '.';
}

// Draws `text` with its top-left at (x, y) by calling plot(px, py) for each
// lit pixel. Clipping is the caller's job, inside plot.
export function drawText(x, y, text, plot) {
  let cursor = x;
  for (const ch of text) {
    const glyph = FONT_5X7[ch] || FONT_5X7['?'];
    for (let col = 0; col < 5; col++) {
      const bits = glyph[col];
      for (let row = 0; row < CHAR_H; row++) {
        if (bits & (1 << row)) plot(cursor + col, y + row);
      }
    }
    cursor += CHAR_W;
  }
}
